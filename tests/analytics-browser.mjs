// Build with GA and Meta enabled. Third-party requests are intercepted, never sent.
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE});
try {
 const context=await browser.newContext({viewport:{width:390,height:844}});
 let googleRequests=0;
 await context.route('https://getreplypass.com/**',async route=>{
  if (route.request().headers()['next-router-prefetch']) { await route.abort(); return; }
  const u=new URL(route.request().url());
  const response=await route.fetch({url:(process.env.TEST_APP_URL||'http://127.0.0.1:3003')+u.pathname+u.search});
  await route.fulfill({response});
 });
 await context.route(/https:\/\/[^/]*(googletagmanager|google-analytics)\.com\//,async route=>{googleRequests++;await route.fulfill({body:'',contentType:'text/javascript'});});
 await context.route('https://connect.facebook.net/**',async route=>{await route.fulfill({body:'',contentType:'text/javascript'});});
 await context.route('https://static.ads-twitter.com/**',async route=>{await route.fulfill({body:'',contentType:'text/javascript'});});
 const page=await context.newPage();
 await page.goto('https://getreplypass.com/?utm_source=Meta&utm_medium=Paid_Social&utm_campaign=GRP-LPV-A&fbclid=secret');
 await page.getByRole('button',{name:'Reject optional'}).waitFor();
 await page.waitForFunction(()=>window.dataLayer?.some(x=>x[1]==='page_view'));
 assert.equal(googleRequests,1);
 let commands=await page.evaluate(()=>window.dataLayer.map(x=>Array.from(x)));
 assert.equal(commands[0][0],'consent');assert.equal(commands[0][2].analytics_storage,'denied');
 assert.equal(commands[0][2].ad_storage,'denied');assert.equal(commands[0][2].ad_user_data,'denied');
 assert.equal(commands[0][2].ad_personalization,'denied');
 assert.equal(commands.filter(x=>x[1]==='page_view').length,1);
 assert.equal(commands.find(x=>x[1]==='page_view')[2].page_location,'https://getreplypass.com/home?utm_source=meta&utm_medium=paid_social&utm_campaign=grp-lpv-a');
 assert.equal(await page.evaluate(()=>document.cookie.includes('_ga=')),false);
 assert.equal(await page.evaluate(()=>!!window.fbq || !!window.twq),false);
 await page.getByRole('button',{name:'Reject optional'}).click();await page.reload();
 await page.waitForFunction(()=>window.dataLayer?.some(x=>x[1]==='page_view'));
 assert.equal(googleRequests,2);
 assert.equal(await page.getByRole('button',{name:'Reject optional'}).count(),0);
 assert.equal(await page.evaluate(()=>window.dataLayer[0][2].analytics_storage),'denied');
 assert.equal(await page.evaluate(()=>document.cookie.includes('_ga=')),false);
 assert.equal(await page.evaluate(()=>!!window.fbq || !!window.twq),false);
 await page.getByRole('button',{name:'Cookie preferences',exact:true}).click();
 await page.getByRole('checkbox',{name:/Google Analytics/}).check();
 const metaChoice=page.getByRole('checkbox',{name:/Meta Pixel/});
 if (await metaChoice.count()) await metaChoice.check();
 await page.getByRole('checkbox',{name:/X Pixel/}).check();
 await page.getByRole('button',{name:'Save choices'}).click();
 await page.waitForFunction(()=>window.dataLayer?.some(x=>x[0]==='consent'&&x[1]==='update'));
 commands=await page.evaluate(()=>window.dataLayer.map(x=>Array.from(x)));
 assert.equal(commands[0][0],'consent');assert.equal(commands[0][2].analytics_storage,'denied');
 assert.equal(commands.find(x=>x[1]==='update')[2].analytics_storage,'granted');
 assert.equal(commands.filter(x=>x[1]==='page_view').length,1);
 assert.equal(commands.find(x=>x[1]==='page_view')[2].page_location,'https://getreplypass.com/home?utm_source=meta&utm_medium=paid_social&utm_campaign=grp-lpv-a');
 await page.waitForTimeout(1800);
 assert.equal(await page.evaluate(()=>window.dataLayer.filter(x=>x[1]==='page_view').length),1);
 assert.equal(await page.evaluate(()=>!!window.fbq),true);
 assert.equal(await page.evaluate(()=>window.fbq.queue.filter(x=>x[0]==='track'&&x[1]==='PageView').length),1);
 await page.goto('https://getreplypass.com/@stella?private=secret');
 await page.waitForFunction(()=>window.dataLayer?.some(x=>x[1]==='page_view'));
 const payload=await page.evaluate(()=>JSON.stringify(window.dataLayer));assert.ok(!payload.includes('secret'));assert.ok(!payload.includes('@stella'));
 await page.getByRole('button',{name:'Cookie preferences',exact:true}).click();
 await page.getByRole('button',{name:'Reject optional'}).click();await page.waitForLoadState('load');
 await page.reload();const before=googleRequests;await page.reload();assert.equal(googleRequests,before+1);
 assert.equal(await page.evaluate(()=>window.dataLayer[0][2].analytics_storage),'denied');
 assert.equal(await page.evaluate(()=>document.cookie.includes('_ga=')),false);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 console.log('PASS cookieless default/reject/withdraw, opt-in, sanitized page views, mobile overflow; third-party requests intercepted.');
} finally {await browser.close();}
